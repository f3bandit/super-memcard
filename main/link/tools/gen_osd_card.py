"""Phosphor's OSD card (RetroAchievements pop-ups over a game): its fonts and icons as 1-bit C tables, for MiSTer's
1-bit OSD: a pixel font (Pixel Operator, CC0) drawn at its own size, and icons drawn on the pixel grid.
usage: gen_osd_card.py [phosphor_osd_font.h]. Needs Pillow (the header it writes is kept in the repository).
Copyright (C) 2026 f3bandit. GPL-3.0."""
import sys
from PIL import Image, ImageDraw, ImageFont
CHARS = list(range(32, 127)) + list(range(160, 256))   # ASCII and Latin-1 (titles: Pokémon, 1080° Snowboarding...)
out = sys.argv[1] if len(sys.argv) > 1 else 'phosphor_osd_font.h'

def font_table(name, path, size, track=0):
    f = ImageFont.truetype(path, size)
    asc, desc = f.getmetrics()
    base = f.getbbox('H', mode='1')[3]                                   # the baseline: under the capitals
    top = min(f.getbbox(chr(c), mode='1')[1] for c in range(33, 127))   # (accented capitals may go above: cut)   # trim the empty rows above the tallest glyph
    h = asc + desc - top
    s = 'static const uint8_t %s_base = %d;\n' % (name, base - min(f.getbbox(chr(c), mode='1')[1] for c in range(33, 127)))
    s += 'static const uint8_t %s_h = %d;\nstatic const struct { uint8_t w; uint32_t r[%d]; } %s[%d] = {\n' % (name, h, h, name, len(CHARS))
    for c in CHARS:
        ch = chr(c)
        w = int(round(f.getlength(ch, mode='1'))) + track
        im = Image.new('1', (w + 8, h), 0)
        d = ImageDraw.Draw(im)
        d.fontmode = '1'
        d.text((0, -top), ch, font=f, fill=1)
        rows = []
        for y in range(h):
            v = 0
            for x in range(min(w + 8, 32)):
                if im.getpixel((x, y)): v |= 1 << x
            rows.append(v)
        s += '\t{%d, {%s}},   // %r\n' % (w, ','.join('0x%x' % r for r in rows), ch)
    return s + '};\n'

