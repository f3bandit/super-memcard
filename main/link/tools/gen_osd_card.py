IW, IH = 24, 24
def icon(name, art):
    rows = art.strip('\n').split('\n')
    assert all(len(r) == IW for r in rows) and len(rows) <= IH, name
    pad = (IH - len(rows)) // 2
    rows = ['.' * IW] * pad + rows + ['.' * IW] * (IH - pad - len(rows))
    return 'static const uint32_t %s[%d] = {%s};\n' % (name, IH, ','.join(
        '0x%x' % sum(1 << x for x, c in enumerate(r) if c == 'X') for r in rows))

